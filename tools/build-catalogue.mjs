#!/usr/bin/env node
// Writes skill/reference/rules.md from whatever is in rules/.
//
// It used to be generated inside tools/build-rules.mjs, which ports two vendor
// sets, so it listed those two and nothing else. That was 38 rules of the 117
// that ship, under a heading calling itself the built-in catalogue. Reading
// rules/index.json instead means a new set appears here by existing.
//
//   node tools/build-catalogue.mjs           write it
//   node tools/build-catalogue.mjs --check   fail if it is out of date

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join, dirname } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(readFileSync(join(ROOT, p), 'utf8'));

const clean = (t) => String(t ?? '').replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
const lines = ['# Rule catalogue', '',
  'Generated by `node tools/build-catalogue.mjs` from everything in `rules/`, so',
  'it cannot drift. Every rule id below works with `--select` and `--ignore`, and',
  '`explain <id>` prints its examples and its evidence.', ''];

let total = 0;
for (const file of read('rules/index.json').sets) {
  const set = read(`rules/${file}`);
  lines.push(`## ${set.title || set.name}: \`${set.name}\``, '',
    clean(set.description).slice(0, 400), '',
    '| rule | flags | fix |', '|---|---|---|');
  for (const r of set.rules) {
    total += 1;
    lines.push(`| \`${r.id}\` | ${clean(r.description).slice(0, 150)} | ${clean(r.suggest)} |`);
  }
  lines.push('');
}
lines.push(`${total} rules in ${read('rules/index.json').sets.length} sets.`, '');

const out = lines.join('\n');
const path = join(ROOT, 'skill/reference/rules.md');
if (process.argv.includes('--check')) {
  const now = readFileSync(path, 'utf8');
  if (now !== out) {
    console.error('skill/reference/rules.md is out of date; run node tools/build-catalogue.mjs');
    process.exit(1);
  }
  console.log(`skill/reference/rules.md is current (${total} rules)`);
} else {
  writeFileSync(path, out);
  console.log(`skill/reference/rules.md  ${total} rules in ${read('rules/index.json').sets.length} sets`);
}
