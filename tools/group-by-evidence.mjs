#!/usr/bin/env node
// Regroups every slop rule by how it actually behaved on the audit corpus,
// rather than by where it came from. Emits three sets into candidates/.
// Re-run whenever the corpus grows: the grouping is derived, never hand-picked.
//   AUDIT=/path/to/corpus node tools/group-by-evidence.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { compileRuleSet } from '../js/engine.mjs';

const ROOT = new URL('..', import.meta.url).pathname;
const D = process.env.AUDIT || join(ROOT, 'audit');

const raw = [];
for (const d of ['rules', 'candidates']) for (const f of readdirSync(join(ROOT, d))) {
  if (!f.endsWith('.json') || f === 'index.json') continue;
  const j = JSON.parse(readFileSync(join(ROOT, d, f), 'utf8'));
  // Skip style profiles, the variant bench, and this tool's own output.
  if (!j.rules || j.role === 'style' || j.name === 'variants' || j.name.startsWith('measured-')) continue;
  const compiled = compileRuleSet(j, j.name);
  j.rules.forEach((def, i) => raw.push({ def, run: compiled.rules[i], set: j.name }));
}
const load = (k) => readdirSync(join(D, k)).filter((f) => f.endsWith('.txt'))
  .map((f) => readFileSync(join(D, k, f), 'utf8'));
const H = load('human'), A = load('ai');
const docs = (r, s) => s.filter((t) => { try { return r.find(t).length; } catch { return false; } }).length;
const hits = (r, s) => s.reduce((a, t) => { try { return a + r.find(t).length; } catch { return a; } }, 0);

const GROUPS = { proven: [], even: [], noisy: [], untested: [] };
for (const { def, run, set } of raw) {
  const hd = docs(run, H), ad = docs(run, A), hh = hits(run, H), ah = hits(run, A);
  const copy = { ...def, from: set,
    evidence: `On the audit corpus: ${hh} hit${hh === 1 ? '' : 's'} in ${hd}/${H.length} human documents, `
      + `${ah} in ${ad}/${A.length} AI documents.` };
  if (!hh && !ah) { copy.evidence = 'Never fired on the audit corpus, on either side. No evidence either way.';
                    GROUPS.untested.push(copy); }
  else if (ah > 0 && (hd === 0 || ah >= hh * 3)) GROUPS.proven.push(copy);
  else if (hh > ah) GROUPS.noisy.push(copy);
  else GROUPS.even.push(copy);   // fired about equally: no signal, not a pass
}

const META = {
  proven: ['Measured: fires on AI prose',
    'Rules that fired on AI prose and either never touched a human document or hit AI at least three times as often. Grouped by how they behaved, not by where they came from, so the source of each is recorded in its "from" field. Generated by tools/group-by-evidence.mjs against the corpus described in research/audit.md; re-run it when the corpus grows.'],
  even: ['Measured: no signal',
    'Rules that fired about as often on human prose as on AI prose. They carry no information about authorship either way on this corpus. Still useful as style flags, which is what they were built for.'],
  noisy: ['Measured: fires more on human prose',
    'Rules that hit human prose more often than AI prose on the audit corpus. Not wrong, and not removed from their original sets: a worn phrase is worth flagging whoever wrote it. But they are weak evidence about authorship and this set exists to say so in one place.'],
  untested: ['Measured: never fired',
    'Rules that fired on neither corpus. Silence is not failure; a rule for a phrase that did not come up says nothing about itself. This set exists so the untested part of the library is visible rather than assumed good.'],
};
for (const [key, rules] of Object.entries(GROUPS)) {
  writeFileSync(join(ROOT, 'candidates', `measured-${key}.json`), JSON.stringify({
    name: `measured-${key}`, version: '0.1.0', slop: '0.1.0',
    title: META[key][0], description: META[key][1],
    source: 'https://github.com/bheijden/slop/blob/main/research/audit.md',
    rules: rules.map((r) => ({ ...r, default: 'off' })),
  }, null, 2) + '\n');
  console.log(`measured-${key}: ${rules.length} rules`);
}
